"""The whole application in rest mode against the sandbox, as the Viewer-only principal.

Collect real run history, detect incidents with the deterministic rules, and investigate them with the typed
read-only tools. Uses the failed runs left by ``scripts/live-estate/seed-history.sh`` (the detection window is widened
to 31 days so that history, not the clock, decides what is found) and ``contracts.sandbox.json`` generated by
``scripts/live-estate/create.sh``.
"""

from __future__ import annotations

import os
from collections.abc import AsyncIterator
from datetime import timedelta
from pathlib import Path

import pytest

from orqentis.bootstrap import Container, build_container
from orqentis.config.settings import Settings
from orqentis.domain.events import EventType
from orqentis.domain.incidents import Incident
from orqentis.domain.principals import Principal, PrincipalKind
from orqentis.domain.taxonomy import IncidentCategory
from orqentis.fabric.write import DisabledFabricWriteClient
from orqentis.incidents.detection import DetectionEngine

REPO = Path(__file__).resolve().parents[2]
CONTRACTS = REPO / "scripts" / "live-estate" / "contracts.sandbox.json"
OPERATOR = Principal(
    id="live.operator@example.invalid",
    display_name="Live operator",
    kind=PrincipalKind.HUMAN,
    roles=frozenset({"FabricOps.Operator"}),
)


@pytest.fixture
async def container(tmp_path: Path) -> AsyncIterator[Container]:
    if not CONTRACTS.is_file():
        pytest.fail(
            "scripts/live-estate/contracts.sandbox.json is missing; run scripts/live-estate/create.sh --contracts-only"
        )
    settings = Settings(
        _env_file=None,  # type: ignore[call-arg]
        fabric_mode="rest",  # type: ignore[arg-type]
        auth_mode="service_principal",  # type: ignore[arg-type]
        tenant_id=os.environ["AZURE_TENANT_ID"],
        contracts_path=CONTRACTS,
        data_dir=tmp_path / "var",
        fixtures_dir=REPO / "fixtures",
        runbooks_dir=REPO / "runbooks",
        clock="system",  # type: ignore[arg-type]
    )
    c = await build_container(settings, reset=True)
    try:
        yield c
    finally:
        await c.aclose()


async def _detect_all(c: Container) -> tuple[list[Incident], dict[str, str]]:
    ingestion, _ = await c.collect_and_detect()
    wide = DetectionEngine(c.incidents, c.clock, window=timedelta(days=31))
    await wide.process(ingestion.new_events)
    return await c.incidents.repository.list(), ingestion.errors


async def test_catalog_is_the_sandbox_estate_and_nothing_else(container: Container) -> None:
    catalog = container.catalog
    assert {w.display_name for w in catalog.workspaces.values()} == {
        "FabricOps Sandbox [DEV]",
        "FabricOps Sandbox [TEST]",
        "FabricOps Sandbox [PROD]",
        "FabricOps Sandbox Consumer",
    }
    assert {dp.id for dp in catalog.data_products.values()} == {
        "dp-sandbox-customers-dev",
        "dp-sandbox-customers-test",
        "dp-sandbox-customers-prod",
    }
    assert len(catalog.slas) == 3
    assert isinstance(container.write_client, DisabledFabricWriteClient)


async def test_collection_reads_runs_and_reports_the_refresh_gap(container: Container) -> None:
    ingestion, _ = await container.collect_and_detect()
    types = {e.event_type for e in ingestion.new_events}
    assert {EventType.PIPELINE_RUN_SUCCEEDED, EventType.PIPELINE_RUN_FAILED} <= types
    # Viewer cannot read Power BI refresh history (docs/security.md section 10): reported, not fatal.
    assert set(ingestion.errors) == {"semantic-model-refreshes"}
    assert "403" in ingestion.errors["semantic-model-refreshes"]


async def test_failed_runs_become_incidents_and_investigations_stay_grounded(container: Container) -> None:
    incidents, _ = await _detect_all(container)
    by_title = {i.incident_id: i for i in incidents}
    assert len(by_title) >= 3, "seed the failed runs: scripts/live-estate/seed-history.sh"
    assert {i.environment.value for i in incidents} >= {"TEST"}
    assert {i.primary_item_name for i in incidents} == {"ingest_customers"}

    categories: set[str] = set()
    for incident in incidents:
        investigated, _ = await container.investigations.investigate(incident.incident_id, actor=OPERATOR)
        evidence_ids = {e.evidence_id for e in investigated.evidence}
        assert evidence_ids, incident.incident_id
        assert all(set(f.evidence_ids) <= evidence_ids for f in investigated.findings)  # grounding
        categories.add(str(investigated.category))

    # The injected timeout and the Entra-style authentication failure are recognised from real payloads.
    assert IncidentCategory.PIPELINE_TIMEOUT.value in categories
    assert IncidentCategory.AUTH_FAILURE.value in categories
